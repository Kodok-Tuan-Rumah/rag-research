"""Index results/metrics/ and flag what needs attention.

`results/metrics/` contains experiment and acceptance evidence across several
datasets and project phases. It is the
project's evidence, so nothing is deleted by this script — the point is that a
reader can tell which file to open, and that duplicates and stale copies are
visible rather than discovered by accident.

What it reports:

- an inventory grouped by the investigation that produced it
- `.json` files with no companion `.md`, i.e. a number with no written note
  explaining what it measured
- near-duplicates: a dated artifact plus a later replica of the same thing
- files whose recorded numbers contradict the frozen baseline

Run:  python scripts/build_evidence_index.py [--check]
      --check exits non-zero when the index on disk is stale.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys
from collections import defaultdict

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

METRICS = REPO_ROOT / "results" / "metrics"
INDEX_JSON = METRICS / "INDEX.json"
INDEX_MD = METRICS / "INDEX.md"
BASELINE = REPO_ROOT / "results" / "metrics" / "k1_baseline_freeze.json"

# Which investigation produced each artifact. Anything unmatched lands in
# "other" rather than being hidden.
GROUPS = [
    ("k1", "K1 — baseline freeze, generation stability, coverage audits"),
    ("k2", "K2 — RAGAS lineage and evidence integrity"),
    ("k3", "K3 — REFERENCES chunk impact"),
    ("k4", "K4 — over-engineering causes"),
    ("k5", "K5 — proposals needing approval"),
    ("k7", "K7 — coverage, latency, forensics, reranker decision"),
    ("j", "Phase J — evaluation gate and statistical sufficiency"),
    ("h", "Phase H — failure taxonomy and per-query forensics"),
    ("fase_", "Phase F — reranker ablation"),
    ("rrf", "RRF mechanism and regression investigations"),
    ("reranker", "Reranker value, latency and depth"),
    ("retrieval", "Retrieval stage benchmarks"),
    ("gold", "Gold label audits"),
    ("postfix", "Post-fix verification"),
    ("canonical", "Canonical baseline snapshots"),
    ("ablation", "Ablations"),
    ("d3", "D3 consistency audit"),
    ("d7", "D7 candidate selection"),
    ("eval_set", "Eval set label audit"),
    ("evidence", "Evidence inventory"),
    ("filter", "Filter precision"),
    ("latency", "Latency budget"),
    ("per_query", "Per-query regression"),
    ("q1", "Q15/Q20 forensics"),
    ("q2", "Q15/Q20 forensics"),
    ("stage", "Stage latency"),
    ("phase_h", "Phase H"),
    ("phase1_smoke", "Phase 1 — generation and abstention acceptance"),
    ("coverage", "Coverage"),
]

KNOWN_STALE = {
    "fase_f_reranker_ablation.json": (
        "mtime 2026-10-05 predates commit 50796bf (2026-10-07); its 0.8571 is "
        "stale. Replicated at fase_f_reranker_ablation_replica_20261010.json."
    ),
}


def _group(name: str) -> str:
    for prefix, label in GROUPS:
        if name.startswith(prefix):
            return label
    return "other — not classified"


def _sha(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def build() -> dict:
    files = sorted(p for p in METRICS.iterdir() if p.is_file())
    files = [p for p in files if p.name not in ("INDEX.json", "INDEX.md")]

    grouped: dict[str, list[dict]] = defaultdict(list)
    unexplained: list[str] = []
    for path in files:
        entry = {
            "name": path.name,
            "bytes": path.stat().st_size,
            "ext": path.suffix.lstrip("."),
            "sha256_12": _sha(path),
        }
        grouped[_group(path.name)].append(entry)

        if path.suffix == ".json":
            companion = path.with_suffix(".md")
            if not companion.exists():
                unexplained.append(path.name)

    replicas: dict[str, list[str]] = defaultdict(list)
    for path in files:
        m = re.match(r"^(.*?)_replica_\d{8}\.", path.name)
        if m:
            replicas[m.group(1) + ".json"].append(path.name)

    baseline = {}
    if BASELINE.exists():
        baseline = json.loads(BASELINE.read_text(encoding="utf-8")).get("stages", {})

    return {
        "total_files": len(files),
        "by_group": {label: grouped[label] for label in sorted(grouped)},
        "json_without_companion_md": sorted(unexplained),
        "replica_pairs": {k: sorted(v) for k, v in sorted(replicas.items())},
        "known_stale": {k: v for k, v in sorted(KNOWN_STALE.items())
                        if (METRICS / k).exists()},
        "baseline_reference": str(BASELINE.relative_to(REPO_ROOT)),
        "baseline_stage_count": len(baseline),
    }


def render_md(payload: dict) -> str:
    out = [
        "# Evidence index — `results/metrics/`",
        "",
        "Generated by `scripts/build_evidence_index.py`. Nothing here is deleted;",
        "this exists so a reader knows which file answers which question, and so",
        "duplicates and stale copies are visible instead of discovered by accident.",
        "",
        f"**{payload['total_files']} files.** "
        f"Baseline of record: `{payload['baseline_reference']}` "
        f"({payload['baseline_stage_count']} stages).",
        "",
    ]

    out += ["## Needs a written note", "",
            "`.json` files with no companion `.md` — a number with no record of what",
            "it measured or whether it still holds.", ""]
    if payload["json_without_companion_md"]:
        out += [f"- `{n}`" for n in payload["json_without_companion_md"]]
    else:
        out.append("None. Every `.json` has a companion `.md`.")

    out += ["", "## Duplicate measurements", ""]
    if payload["replica_pairs"]:
        for original, copies in payload["replica_pairs"].items():
            out.append(f"- `{original}` replicated: " + ", ".join(f"`{c}`" for c in copies))
    else:
        out.append("None.")

    out += ["", "## Known stale", ""]
    if payload["known_stale"]:
        for name, why in payload["known_stale"].items():
            out.append(f"- `{name}` — {why}")
    else:
        out.append("None recorded.")

    out += ["", "## Inventory", ""]
    for label, entries in payload["by_group"].items():
        out.append(f"### {label} ({len(entries)})")
        out.append("")
        for e in entries:
            out.append(f"- `{e['name']}` — {e['bytes']:,} B")
        out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if INDEX.json is stale")
    args = parser.parse_args()

    payload = build()
    serialised = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"

    if args.check:
        if not INDEX_JSON.exists():
            print("FAIL: results/metrics/INDEX.json does not exist. "
                  "Run with no --check to generate it.", file=sys.stderr)
            return 1
        if INDEX_JSON.read_text(encoding="utf-8") != serialised:
            print("FAIL: results/metrics/INDEX.json is stale; regenerate it.",
                  file=sys.stderr)
            return 1
        print(f"    {payload['total_files']} files indexed, index current")
        return 0

    INDEX_JSON.write_text(serialised, encoding="utf-8")
    INDEX_MD.write_text(render_md(payload), encoding="utf-8")
    print(f"  {payload['total_files']} files indexed")
    print(f"  .json tanpa companion .md : {len(payload['json_without_companion_md'])}")
    print(f"  pasangan replika          : {len(payload['replica_pairs'])}")
    print(f"  stale terdokumentasi      : {len(payload['known_stale'])}")
    print(f"  -> {INDEX_JSON.relative_to(REPO_ROOT)}")
    print(f"  -> {INDEX_MD.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
